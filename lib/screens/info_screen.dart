  List<Map<String, dynamic>> _searchLessons() {
    List<Map<String, dynamic>> results = [];

    for (var category in categories) {
      for (var lesson in category["lessons"]) {
        if (lesson["title"]
            .toLowerCase()
            .contains(searchQuery.toLowerCase())) {
          results.add(lesson);
        }
      }
    }

    if (showBookmarksOnly) {
      results = results
          .where((l) => bookmarkedLessons.contains(l["id"]))
          .toList();
    }

    return results;
  }

