  double _calculateProgress(List lessons) {
    if (lessons.isEmpty) return 0;

    int done = lessons
        .where((l) => completedLessons.contains(l["id"]))
        .length;

    return done / lessons.length;
  }

  Widget _lessonCard(Map lesson) {
    final id = lesson["id"];

    final isDone = completedLessons.contains(id);
    final isSaved = bookmarkedLessons.contains(id);
    final selectedCategory = categories[selectedIndex];

    return GestureDetector(
      onTap: () async {
        await Navigator.push(
          context,
          MaterialPageRoute(
            builder: (_) => LessonDetailPage(
              lesson: lesson,
              category: selectedCategory["title"] as String,
              isDone: completedLessons.contains(id),
              isSaved: bookmarkedLessons.contains(id),

              onComplete: () {
                setState(() {
                  if (completedLessons.contains(id)) {
                    completedLessons.remove(id);
                  } else {
                    completedLessons.add(id);
                  }
                });
                _saveData();
              },

              onBookmark: () {
                setState(() {
                  if (bookmarkedLessons.contains(id)) {
                    bookmarkedLessons.remove(id);
                  } else {
                    bookmarkedLessons.add(id);
                  }
                });
                _saveData();
              },
            ),
          ),
        );
      },
      child: Container(
        margin: const EdgeInsets.only(bottom: 14),
        decoration: BoxDecoration(
          color: Colors.white,
          borderRadius: BorderRadius.circular(16),
          boxShadow: const [
            BoxShadow(color: Colors.black12, blurRadius: 8),
          ],
        ),
        child: Column(
          children: [
            Hero(
              tag: id,
              child: ClipRRect(
                borderRadius:
                const BorderRadius.vertical(top: Radius.circular(16)),
                child: Image.network(
                  lesson["image"],
                  height: 140,
                  width: double.infinity,
                  fit: BoxFit.cover,
                ),
              ),
            ),
            ListTile(
              title: Text(lesson["title"]),
              subtitle: Text(isDone ? "Completed ✅" : "Tap to learn"),
              trailing: Icon(
                isSaved ? Icons.bookmark : Icons.bookmark_border,
                color: primaryGreen,
              ),
            ),
          ],
        ),
      ),
    );
  }
